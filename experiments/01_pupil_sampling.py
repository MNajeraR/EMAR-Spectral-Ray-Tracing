# -*- coding: utf-8 -*-
"""
EMAR - Pupil Sampling Examples
==============================

This script provides a visual comparison of the pupil-sampling methods
implemented in ``utils.emar_utils``.

The pupil coordinates used by PyZDDE are normalized coordinates:

    Px, Py in [-1, 1]

with the circular pupil defined by:

    Px**2 + Py**2 <= 1

Two sampling strategies are currently illustrated:

1. Random sampling
   Rays are randomly distributed over the area of the normalized pupil.
   The radial coordinate is sampled as sqrt(u), where u is uniformly
   distributed in [0, 1], producing a uniform spatial density over the
   circular pupil.

2. Hexapolar sampling
   Rays are distributed deterministically in concentric rings. The number
   of points increases with ring radius, producing the characteristic
   hexapolar sampling pattern.

This script does not perform any Zemax ray tracing. Its only purpose is
to visualize and verify the pupil coordinates generated by the sampling
functions before using them in the EMAR ray-tracing scripts.

The corresponding sampling functions are defined in:

    utils/emar_utils.py

and the plotting routine is defined in:

    utils/emar_plots.py

Author
------
Morgan R. Najera

Date
----
September 2026
"""


##############################################################
# Imports
##############################################################

# EMAR project path
from pathlib import Path
import sys
PROJECT_DIR = Path(__file__).resolve().parent.parent
if str(PROJECT_DIR) not in sys.path:
    sys.path.insert(
        0,
        str(PROJECT_DIR)
    )

# General EMAR utilities.
#
# This module contains the pupil-sampling functions used by the
# ray-tracing scripts.
from utils import emar_utils


# Plotting utilities.
#
# The same plotting function is used for both sampling methods,
# allowing their pupil distributions to be compared directly.
from utils import emar_plots


##############################################################
# Random pupil sampling
##############################################################

# Generate 100 normalized pupil coordinates randomly distributed
# over the area of the circular pupil.
#
# A fixed seed is used so that the same pupil distribution is
# generated every time the script is executed. This is useful for
# reproducibility when comparing different optical configurations,
# surfaces, or versions of the Zemax model.

px, py = emar_utils.sample_random_pupil(
    n_rays=100,
    seed=123
)


# Visualize the generated normalized pupil coordinates.
#
# No optical ray tracing is performed here. The figure simply shows
# the locations at which rays would enter the pupil in subsequent
# Zemax calculations.

emar_plots.plot_pupil_sampling(
    px,
    py,
    title="Random pupil sampling — 100 rays"
)


##############################################################
# Hexapolar pupil sampling
##############################################################

# Generate a deterministic hexapolar sampling pattern.
#
# The pupil consists of one central ray plus a sequence of
# concentric rings. For n_rings = 5, the current implementation
# generates a total of 91 pupil points.

px, py = emar_utils.sample_hexapolar_pupil(
    n_rings=5
)


# Visualize the hexapolar pupil distribution using the same plotting
# routine employed above for the random sampling.

emar_plots.plot_pupil_sampling(
    px,
    py,
    title="Hexapolar pupil sampling — 91 rays"
)