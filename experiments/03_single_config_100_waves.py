# -*- coding: utf-8 -*-
"""
EMAR - Single Configuration with 100 Wavelengths
=================================================

This script extends the analysis performed in
``02_single_config_original_wavelengths.py`` by introducing a finer
spectral sampling within a single Zemax configuration.

Instead of tracing only the 11 wavelengths originally defined in the
Zemax wavelength table, 100 wavelengths are generated between the
minimum and maximum wavelengths associated with the selected
configuration.

For the current example:

    Configuration       = 2
    Surface             = 26
    Spectral samples    = 100 wavelengths
    Pupil samples       = 100 rays

For each wavelength, WAVE 1 is temporarily modified through the Zemax
Multi-Configuration Editor (MCE). After updating the optical system,
the wavelength actually used by Zemax is read back and compared with
the requested value.

A complete pupil footprint is then generated by tracing the same set
of normalized pupil coordinates for every wavelength.

The original value of WAVE 1 is restored after the calculation so that
the Zemax optical model is not permanently modified.

This script introduces the basic workflow later generalized to
multiple configurations:

    MCE spectral range
            |
            v
    Generate wavelength sampling
            |
            v
    Modify WAVE 1 in MCE
            |
            v
    Update Zemax
            |
            v
    Verify wavelength
            |
            v
    Trace pupil
            |
            v
    Store footprint
            |
            v
    Restore original MCE value

Author
------
Morgan R. Najera

Date
----
September 2026
"""


##############################################################
# Imports
##############################################################

import numpy as np
import matplotlib.pyplot as plt
import pyzdde.zdde as pyz
# EMAR project path
from pathlib import Path
import sys
PROJECT_DIR = Path(__file__).resolve().parent.parent

if str(PROJECT_DIR) not in sys.path:
    sys.path.insert(
        0,
        str(PROJECT_DIR)
    )
from utils import emar_utils

##############################################################
# Analysis parameters
##############################################################

# Zemax multi-configuration to analyze.

config = 2


# Surface where the ray coordinates will be evaluated.

surf = 26


# Number of wavelengths used to sample the spectral range.

n_wavelengths = 100


# Number of rays used to sample the normalized pupil.

n_rays = 100


# MCE rows containing WAVE 1 and WAVE 11.
#
# These two wavelengths define the spectral limits of the
# selected configuration.

row_wave1 = 2

row_wave11 = 12


##############################################################
# Zemax optical model
##############################################################

# ZEMAX_DIR is defined in utils/emar_utils.py and points to the
# directory containing the Zemax optical models.

file_path = (
    emar_utils.ZEMAX_DIR
    / "WP - Con prismas diseñados - camara.zmx"
)


##############################################################
# Connect to Zemax
##############################################################

ln = pyz.createLink()


# Load the EMAR optical model.

ln.zLoadFile(
    str(file_path)
)


##############################################################
# Select configuration
##############################################################

# Activate the requested Zemax multi-configuration.

ln.zSetConfig(
    config
)

ln.zGetUpdate()


##############################################################
# Read spectral limits from the MCE
##############################################################

# The minimum and maximum wavelengths are obtained directly
# from the Multi-Configuration Editor rather than being entered
# manually.
#
# This ensures that the spectral sampling remains tied to the
# selected Zemax configuration.

wave_min = ln.zGetMulticon(
    config,
    row_wave1
).value


wave_max = ln.zGetMulticon(
    config,
    row_wave11
).value


print(
    f"Spectral range: "
    f"{wave_min:.6f} - {wave_max:.6f} um"
)


##############################################################
# Generate wavelength sampling
##############################################################

# Generate 100 equally spaced wavelengths between the spectral
# limits of the selected configuration.

wavelengths_um = np.linspace(
    wave_min,
    wave_max,
    n_wavelengths
)


##############################################################
# Save original WAVE 1 MCE data
##############################################################

# WAVE 1 will be temporarily modified during the calculation.
#
# The complete MCE entry is stored here so that both its original
# wavelength and its solve properties can be restored afterwards.

original_wave1 = ln.zGetMulticon(
    config,
    row_wave1
)


##############################################################
# Pupil sampling
##############################################################

# Generate a reproducible random sampling of the normalized pupil.
#
# The same pupil coordinates are used for every wavelength. This
# ensures that changes in the resulting footprints are caused by
# wavelength rather than by a different random pupil realization.

px, py = emar_utils.sample_random_pupil(
    n_rays=n_rays,
    seed=123
)


##############################################################
# Storage dictionary
##############################################################

# Each wavelength will be associated with its complete X-Y
# footprint at the selected surface.

spots_by_wave = {}


##############################################################
# Trace all wavelengths
##############################################################

for wavelength in wavelengths_um:

    ##########################################################
    # Modify WAVE 1 in the Multi-Configuration Editor
    ##########################################################

    # The wavelength value of WAVE 1 is temporarily replaced by
    # the current wavelength of the spectral sampling.
    #
    # The original solve status and associated MCE parameters are
    # preserved.

    ln.zSetMulticon(
        config,
        row_wave1,
        wavelength,
        original_wave1.status,
        original_wave1.pickupRow,
        original_wave1.pickupConfig,
        original_wave1.scale,
        original_wave1.offset
    )


    ##########################################################
    # Update Zemax
    ##########################################################

    # Force Zemax to update the optical system after changing
    # the wavelength in the MCE.

    ln.zGetUpdate()


    ##########################################################
    # Verify wavelength used by Zemax
    ##########################################################

    # Read WAVE 1 from the active Zemax system.
    #
    # This verification was introduced because changing the
    # wavelength without correctly modifying the MCE can result
    # in Zemax continuing to trace the original wavelength.

    wave_zemax = ln.zGetWave(
        1
    ).wavelength


    ##########################################################
    # Trace complete pupil
    ##########################################################

    # Trace the same normalized pupil coordinates for the current
    # wavelength up to the selected surface.

    x, y = emar_utils.trace_pupil(
        ln=ln,
        wave_num=1,
        surf=surf,
        px=px,
        py=py,
        hx=0.0,
        hy=0.0
    )


    ##########################################################
    # Store wavelength footprint
    ##########################################################

    spots_by_wave[
        float(wavelength)
    ] = {
        "x": x.copy(),
        "y": y.copy()
    }


    ##########################################################
    # Diagnostic output
    ##########################################################

    print(
        f"Requested = {wavelength:.6f} um | "
        f"Zemax = {wave_zemax:.6f} um | "
        f"{len(x)}/{n_rays} valid rays"
    )


##############################################################
# Restore original WAVE 1
##############################################################

# Restore the complete original MCE entry so that execution of
# this script does not leave the Zemax model spectrally modified.

ln.zSetMulticon(
    config,
    row_wave1,
    original_wave1.value,
    original_wave1.status,
    original_wave1.pickupRow,
    original_wave1.pickupConfig,
    original_wave1.scale,
    original_wave1.offset
)

ln.zGetUpdate()


##############################################################
# Close Zemax connection
##############################################################

ln.close()


##############################################################
# Calculation summary
##############################################################

print(
    f"\nNumber of wavelengths stored: "
    f"{len(spots_by_wave)}"
)


##############################################################
# Plot complete spectral footprint
##############################################################

# Each wavelength is represented by a different color.
#
# The resulting figure simultaneously shows:
#
#   - the geometrical footprint produced by the pupil,
#   - the spectral displacement with wavelength,
#   - and the orientation of the spectral trace at the
#     selected surface.

fig, ax = plt.subplots(
    figsize=(10, 8)
)


##############################################################
# Wavelength color normalization
##############################################################

cmap = plt.cm.viridis

norm = plt.Normalize(
    wavelengths_um.min(),
    wavelengths_um.max()
)


##############################################################
# Plot wavelength footprints
##############################################################

for wavelength in wavelengths_um:

    spot = spots_by_wave[
        float(wavelength)
    ]

    x = spot["x"]

    y = spot["y"]

    ax.scatter(
        x,
        y,
        s=3,
        color=cmap(norm(wavelength)),
        alpha=0.6
    )


##############################################################
# Wavelength colorbar
##############################################################

sm = plt.cm.ScalarMappable(
    cmap=cmap,
    norm=norm
)

sm.set_array([])

cbar = fig.colorbar(
    sm,
    ax=ax
)

cbar.set_label(
    r"Wavelength [$\mu$m]",
    fontsize=12
)


##############################################################
# Plot format
##############################################################

ax.set_xlabel(
    "X [mm]",
    fontsize=14
)

ax.set_ylabel(
    "Y [mm]",
    fontsize=14
)

ax.set_title(
    f"Configuration {config} - Surface {surf}"
)

ax.tick_params(
    labelsize=12
)

fig.tight_layout()

plt.show()

